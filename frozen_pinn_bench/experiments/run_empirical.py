#!/usr/bin/env python3
"""Empirical branch: measured bench logs -> pointing and HAPS-equivalent link metrics -> figures.

  python experiments/run_empirical.py --session data/empirical/<session>

Log format: docs/empirical_protocol.md. Output: results/empirical/<session>/ (summary.json, data.npz,
figures/). A session marked "synthetic" in session.json is labelled as a dry run in every figure.
"""
import argparse
import json
from pathlib import Path
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
for path in (ROOT, ROOT/'experiments'):
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))
from pat.comm import HAPSReceiver, LinkModel
from pat.empirical import analyse, load_session
from pat.spec import load_spec
from make_figures import empirical_figures


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--session', required=True)
    parser.add_argument('--config', default='config/bench.json')
    parser.add_argument('--name', help='output name (default: session folder name)')
    args = parser.parse_args()
    session = ROOT/args.session
    meta, runs = load_session(session)
    spec = load_spec(ROOT/args.config)
    ev = spec.raw['evaluation']
    link = LinkModel(ev)
    receivers = {f'r{int(round(r*1e6))}': HAPSReceiver(ev['comm'], r, spec.psd_lever) for r in ev['comm']['detector_radii_m']}
    summary, arrays = analyse(meta, runs, spec, link, receivers)
    out = ROOT/'results'/'empirical'/(args.name or session.name)
    if out.exists():
        raise SystemExit(f'{out} exists; choose a new --name')
    out.mkdir(parents=True)
    banner = 'SYNTHETIC DRY RUN - logs generated by the bench model, not measured' if meta.get('synthetic') else None
    summary.update(session=str(session.relative_to(ROOT)), session_meta=meta, banner=banner, config=spec.raw)
    (out/'summary.json').write_text(json.dumps(summary, indent=2)+'\n')
    np.savez_compressed(out/'data.npz', **arrays)
    idx = empirical_figures(out)
    print(f'{len(runs)} runs, {len(idx.items)} figures -> {out}')


if __name__ == '__main__':
    main()
